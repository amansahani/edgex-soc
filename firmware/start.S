    /* stack at top of 64 KiB SRAM */
    lui sp, 0x10        /* 0x00010000 >> 12 */

    /* call main */
    la ra, main
    jr ra

    /* trap vector (ebreak from main lands here) */
    .align 4
1:  wfi
    j 1b
